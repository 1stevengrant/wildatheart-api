<?php

namespace Ghijk\StatamicTypescriptGenerator\Generators;

use Illuminate\Support\Facades\File;
use Ghijk\StatamicTypescriptGenerator\Mappers\NestedType;
use Ghijk\StatamicTypescriptGenerator\Mappers\FieldTypeMapper;
use Ghijk\StatamicTypescriptGenerator\Parsers\BlueprintParser;
use Ghijk\StatamicTypescriptGenerator\Parsers\ParsedBlueprint;

class TypeScriptGenerator
{
    protected array $generatedTypes = [];

    protected array $nestedTypes = [];

    public function __construct(
        protected BlueprintParser $blueprintParser,
        protected FieldTypeMapper $fieldTypeMapper
    ) {}

    /**
     * Generate TypeScript definitions for all blueprints.
     */
    public function generate(array $options = []): array
    {
        $outputPath = $options['output_path'] ?? config('statamic-typescript.output_path');
        $collections = $options['collections'] ?? null;
        $includeRunway = $options['include_runway'] ?? true;

        $this->generatedTypes = [];
        $this->nestedTypes = [];

        // Discover blueprints
        $blueprintPaths = $this->blueprintParser->discoverBlueprints();

        // Filter by collections if specified
        if ($collections) {
            $blueprintPaths = array_filter($blueprintPaths, function ($path) use ($collections) {
                foreach ($collections as $collection) {
                    if (str_contains($path, "collections/$collection/")) {
                        return true;
                    }
                }

                return false;
            });
        }

        // Filter Runway if disabled
        if (! $includeRunway) {
            $blueprintPaths = array_filter($blueprintPaths, function ($path) {
                return ! str_contains($path, 'vendor/runway/');
            });
        }

        // Parse each blueprint
        $parsedBlueprints = [];
        foreach ($blueprintPaths as $path) {
            try {
                $parsed = $this->blueprintParser->parse($path);
                $parsedBlueprints[] = $parsed;
            } catch (\Exception $e) {
                // Log error but continue processing
                logger()->warning("Failed to parse blueprint: $path", ['error' => $e->getMessage()]);
            }
        }

        // Generate TypeScript
        $typescript = $this->generateTypeScript($parsedBlueprints);

        // Write output
        $this->writeOutput($outputPath, $typescript);

        return [
            'types_count' => count($this->generatedTypes) + count($this->nestedTypes),
            'blueprints_count' => count($parsedBlueprints),
        ];
    }

    /**
     * Generate the complete TypeScript output.
     */
    protected function generateTypeScript(array $blueprints): string
    {
        $lines = [
            '/**',
            ' * Statamic TypeScript Definitions',
            ' * Auto-generated by statamic:generate-types',
            ' * DO NOT EDIT MANUALLY',
            ' */',
            '',
        ];

        $rootNamespace = config('statamic-typescript.namespace', 'Statamic.Data');
        $lines[] = "declare namespace $rootNamespace {";

        // Generate base types
        if (config('statamic-typescript.base_types.StatamicAsset', true)) {
            $lines[] = $this->generateBaseTypes();
        }

        // Group blueprints by namespace
        $grouped = $this->groupByNamespace($blueprints);

        foreach ($grouped as $namespace => $nsBlueprints) {
            if (! empty($namespace)) {
                $lines[] = '';
                $lines[] = '    // ========================================================================';
                $lines[] = "    // $namespace";
                $lines[] = '    // ========================================================================';
                $lines[] = '';
                $lines[] = "    namespace {$namespace} {";
                $indent = '        ';
            } else {
                $indent = '    ';
            }

            foreach ($nsBlueprints as $blueprint) {
                $interfaceCode = $this->generateInterface($blueprint, $indent);
                $lines[] = $interfaceCode;
                $this->generatedTypes[] = $blueprint->getInterfaceName();
            }

            // Add nested types for this namespace
            $nsNestedTypes = array_filter($this->nestedTypes, function ($type) use ($namespace) {
                return ($type['namespace'] ?? '') === $namespace;
            });

            foreach ($nsNestedTypes as $nestedType) {
                $lines[] = '';
                $lines[] = $nestedType['type']->toTypeScript($indent);
            }

            if (! empty($namespace)) {
                $lines[] = '    }';
            }
        }

        $lines[] = '}';

        return implode("\n", $lines);
    }

    /**
     * Generate base type definitions.
     */
    protected function generateBaseTypes(): string
    {
        $types = [];

        $types[] = '    // ========================================================================';
        $types[] = '    // Base Types';
        $types[] = '    // ========================================================================';
        $types[] = '';

        if (config('statamic-typescript.base_types.StatamicAsset', true)) {
            $types[] = '    interface StatamicAsset {';
            $types[] = '        id: string;';
            $types[] = '        url: string;';
            $types[] = '        permalink: string;';
            $types[] = '        alt: string | null;';
            $types[] = '        width: number | null;';
            $types[] = '        height: number | null;';
            $types[] = '        size: number;';
            $types[] = '        extension: string;';
            $types[] = '        mime_type: string;';
            $types[] = '        last_modified: string;';
            $types[] = '    }';
            $types[] = '';
        }

        if (config('statamic-typescript.base_types.StatamicLink', true)) {
            $types[] = '    interface StatamicLink {';
            $types[] = '        url: string | null;';
            $types[] = '    }';
            $types[] = '';
        }

        if (config('statamic-typescript.base_types.StatamicEntryReference', true)) {
            $types[] = '    interface StatamicEntryReference {';
            $types[] = '        id: string;';
            $types[] = '        title: string;';
            $types[] = '        slug: string;';
            $types[] = '        url: string;';
            $types[] = '        collection: string;';
            $types[] = '    }';
            $types[] = '';
        }

        if (config('statamic-typescript.base_types.StatamicTermReference', true)) {
            $types[] = '    interface StatamicTermReference {';
            $types[] = '        id: string;';
            $types[] = '        title: string;';
            $types[] = '        slug: string;';
            $types[] = '        url: string;';
            $types[] = '        taxonomy: string;';
            $types[] = '    }';
            $types[] = '';
        }

        if (config('statamic-typescript.base_types.StatamicUserReference', true)) {
            $types[] = '    interface StatamicUserReference {';
            $types[] = '        id: string;';
            $types[] = '        name: string;';
            $types[] = '        email: string;';
            $types[] = '        avatar: string | null;';
            $types[] = '    }';
            $types[] = '';
        }

        if (config('statamic-typescript.base_types.StatamicBardTextNode', true)) {
            $types[] = '    interface StatamicBardTextNode {';
            $types[] = '        type: string;';
            $types[] = '        content?: StatamicBardTextNode[];';
            $types[] = '        text?: string;';
            $types[] = '        attrs?: Record<string, unknown>;';
            $types[] = '        marks?: Array<{ type: string; attrs?: Record<string, unknown> }>;';
            $types[] = '    }';
            $types[] = '';
        }

        $types[] = '    interface StatamicTableRow {';
        $types[] = '        cells: string[];';
        $types[] = '    }';

        return implode("\n", $types);
    }

    /**
     * Generate an interface for a blueprint.
     */
    protected function generateInterface(ParsedBlueprint $blueprint, string $indent = '    '): string
    {
        $lines = [];
        $lines[] = '';
        $lines[] = "{$indent}interface {$blueprint->getInterfaceName()} {";

        // Add common fields
        $lines[] = "$indent    id: string;";

        foreach ($blueprint->fields as $field) {
            $mapping = $this->fieldTypeMapper->mapField($field, $blueprint->handle);

            if ($mapping === null) {
                continue;
            }

            $lines[] = $mapping->toTypeScript($indent . '    ');

            // Collect nested types
            foreach ($mapping->nestedTypes as $nestedType) {
                if ($nestedType instanceof NestedType) {
                    $this->nestedTypes[] = [
                        'namespace' => $blueprint->namespace,
                        'type' => $nestedType,
                    ];
                }
            }
        }

        $lines[] = "$indent}";

        return implode("\n", $lines);
    }

    /**
     * Group blueprints by namespace.
     */
    protected function groupByNamespace(array $blueprints): array
    {
        $grouped = [];

        foreach ($blueprints as $blueprint) {
            $namespace = $blueprint->namespace;
            if (! isset($grouped[$namespace])) {
                $grouped[$namespace] = [];
            }
            $grouped[$namespace][] = $blueprint;
        }

        // Sort namespaces
        ksort($grouped);

        return $grouped;
    }

    /**
     * Write output to file.
     */
    protected function writeOutput(string $path, string $content): void
    {
        $directory = dirname($path);

        if (! File::isDirectory($directory)) {
            File::makeDirectory($directory, 0755, true);
        }

        // Only write if content has changed
        if (File::exists($path)) {
            $existingContent = File::get($path);

            if ($existingContent === $content) {
                return;
            }
        }

        File::put($path, $content);
    }
}
